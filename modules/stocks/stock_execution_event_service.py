    def export_events(
            self,
            *,
            portfolio_id: Optional[str] = None,
    ) -> list[dict]:
        """
        Export execution events.

        Future versions can serialize directly
        to CSV, Parquet, JSON, or audit packages.
        """

        return self.get_events(
            portfolio_id=portfolio_id,
            limit=1_000_000,
        )

    # ======================================================
    # Maintenance
    # ======================================================

    def delete_events_for_portfolio(
            self,
            portfolio_id: str,
    ) -> int:
        """
        Administrative helper.

        Normally execution events should remain
        immutable and permanent.

        This exists only for development,
        testing, or tenant cleanup.
        """

        if self.db is None:
            return 0

        try:

            result = self.db.execute(

                text(
                    """
                    DELETE
                    FROM stock_execution_events
                    WHERE portfolio_id = :portfolio_id
                    """
                ),

                {
                    "portfolio_id": portfolio_id,
                },
            )

            self.db.commit()

            return int(result.rowcount or 0)

        except SQLAlchemyError:

            logger.exception(
                "Unable to delete execution events."
            )

            try:
                self.db.rollback()
            except Exception:
                pass

            return 0

