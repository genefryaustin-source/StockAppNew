    # ======================================================
    # Query API
    # ======================================================

    def get_events(
            self,
            *,
            portfolio_id: Optional[str] = None,
            order_id: Optional[int] = None,
            position_id: Optional[int] = None,
            symbol: Optional[str] = None,
            event_type: Optional[str] = None,
            limit: int = 250,
    ) -> list[dict]:
        """
        Return execution events using optional filters.
        """

        if self.db is None:
            return []

        sql = """
            SELECT *
            FROM stock_execution_events
            WHERE 1=1
        """

        params: Dict[str, Any] = {}

        if portfolio_id:
            sql += " AND portfolio_id = :portfolio_id"
            params["portfolio_id"] = portfolio_id

        if order_id is not None:
            sql += " AND order_id = :order_id"
            params["order_id"] = order_id

        if position_id is not None:
            sql += " AND position_id = :position_id"
            params["position_id"] = position_id

        if symbol:
            sql += " AND UPPER(symbol) = :symbol"
            params["symbol"] = symbol.upper()

        if event_type:
            sql += " AND event_type = :event_type"
            params["event_type"] = event_type

        sql += """
            ORDER BY event_timestamp DESC
            LIMIT :limit
        """

        params["limit"] = limit

        try:

            rows = (
                self.db.execute(
                    text(sql),
                    params,
                )
                .mappings()
                .all()
            )

            return [dict(r) for r in rows]

        except SQLAlchemyError:

            logger.exception(
                "Unable to load execution events."
            )

            return []

    # ======================================================
    # Event Statistics
    # ======================================================

    def get_statistics(
            self,
            *,
            portfolio_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Build high-level execution statistics.
        """

        events = self.get_events(
            portfolio_id=portfolio_id,
            limit=100000,
        )

        stats = {

            "total_events": len(events),

            "orders_created": 0,

            "orders_submitted": 0,

            "orders_filled": 0,

            "orders_cancelled": 0,

            "orders_rejected": 0,

            "positions_opened": 0,

            "positions_closed": 0,

            "stop_losses": 0,

            "take_profits": 0,
        }

        for event in events:

            event_type = event.get("event_type")

            if event_type == ExecutionEventType.ORDER_CREATED.value:
                stats["orders_created"] += 1

            elif event_type == ExecutionEventType.ORDER_SUBMITTED.value:
                stats["orders_submitted"] += 1

            elif event_type == ExecutionEventType.ORDER_FILLED.value:
                stats["orders_filled"] += 1

            elif event_type == ExecutionEventType.ORDER_CANCELLED.value:
                stats["orders_cancelled"] += 1

            elif event_type == ExecutionEventType.ORDER_REJECTED.value:
                stats["orders_rejected"] += 1

            elif event_type == ExecutionEventType.POSITION_OPENED.value:
                stats["positions_opened"] += 1

            elif event_type == ExecutionEventType.POSITION_CLOSED.value:
                stats["positions_closed"] += 1

            elif event_type == ExecutionEventType.STOP_LOSS_TRIGGERED.value:
                stats["stop_losses"] += 1

            elif event_type == ExecutionEventType.TAKE_PROFIT_TRIGGERED.value:
                stats["take_profits"] += 1

        return stats

    # ======================================================
    # Export API
